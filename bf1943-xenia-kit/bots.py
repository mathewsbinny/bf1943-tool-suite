"""Experiment: server-side bots for BF1943 in Xenia, as a second Xenia patch file.

BF1943's AI was stripped (no AI controller, orders or navigation), but its server still creates players with no
network connection: the leftover AI spawner (SoldierSpawnEntity, 8236bc98) does so. The bots here are created the
same way, then given what a human player gets from the network, and spawned through the human spawn path:

  per server frame, after the server's own player update (8238eb68, called at 0x82391988):
    1. once a human player has a soldier: for each bot,
         createPlayer 82387ef0(manager, 0)          a ServerPlayer with no connection
         addPlayer    8238efd8(manager, p, name)    name as a {begin, end} string
         8240dfe0(server context + 0x44, p)          as the network join does next: the score and stats
                                                    managers (the first run's bots were not on the scoreboard)
         an input state (82627d10(0x168), constructor 822c1478), attached with 8236f230(p, state): the soldier
                                                    reads its controls from it (no frames are pushed yet:
                                                    it stands still)
         ready        82375130(p)                   (also keeps 8238eb68 from giving it its default soldier)
         setTeam      82374f90(p, team)             1 USMC, 2 Japan
         the team's kit by asset name: 82378988(handle, "Objects/Soldiers/US/Assault") finds the loaded
         SoldierEntityData; 82373a28(p + 0x1f4, it) makes it the player's kit (a counted reference)
    2. every frame, each bot:
       gets one neutral input frame, as the server makes for a connection with no input queued (823af4a0):
       822bd4a8(frame) clears it; its sequence number (+0x98) is the current frame's (input state +0x160) plus
       one; +0x80 is the server's time step (the hook's f1; 822f1d70 writes it there for entities without a
       player) and +0x84 is carried over (823a1f80 does the same); 822c15d0(state, frame) pushes it. Test input:
       EIAThrottle (action 0, float at +0x08) = THROTTLE;
       and without a soldier (+0x120), asks to spawn at its base: 82382720(p, spawn). The spawn is found by
       identity, not by list position: in the per-team lists 82343f68(owner, 1 and 2), the first spawn entity
       whose data's Team (entity + 0x14 -> data + 0x88) is the bot's team, turned into a spawn id (822a83a8).
       (With spawn 0, or the first entry of either list, each side's bots spawned on the other side's carrier:
       runs of 2026-10-23.) The server refuses while a respawn delay runs, so this also respawns them.

Stepping: a soldier is advanced only by its virtual +0x104 (822f05c8), which the network path calls once per
input frame it drains from a connection (823b2c80, at 823b2ed4). The physics world skips characters while the
setting Physics.SingleStepCharacter is on (8253e4c8 tests the character's +0xd2, which the soldier constructor sets
from it), and the per-tick update 822f1d70 runs only the last part of the step (+0x114), and only for players with
the AI flag (+0x214). In BFBC2 the setting is probably turned off in levels with AI (LevelData.HasAI; a BFBC2 lead,
unverified), so its physics world steps AI soldiers (research/evidence/ai-soldier-control.json). The bots therefore call +0x104 after each frame they push, and keep
the AI flag at 0 so that 822f1d70 does not apply the input a second time. (Runs of 2026-10-23: without stepping,
with the flag 0 the bots stood at their spawn transform 0.8 m above the deck; with it 1 they stood on the deck
but ignored all input.) Evidence and addresses: operation-rising-sun/research/AGENT_PROGRESS.md (2026-10-22,
"Bots: the server player pipeline", and the 2026-10-23 bot entries). The addresses are this build's (module hash 872BBE31C0FBA21B) only.
"""
import struct
import sys

sys.dont_write_bytecode = True
import ppcasm

PATCH_FILE = '5841097E - Battlefield 1943 - bots experiment.patch.toml'
HEADER = '# Generated by bf1943-xenia-kit/bots.py.'
HOOK = 0x82391988            # bl 0x8238eb68 in the server player update 82391930
HOOK_ORIGINAL = 0x4BFFD1E1   # that bl
CODE = 0x82AAA1C0            # unused, zero: the end of the BINK code section's last page (to 0x82AAB000)
CODE_END = 0x82AAB000
DATA = 0x82D26E10            # unused, zero: after .data, before fieldinf (to 0x82D27000)
DATA_END = 0x82D27000
MAX_BOTS = 23               # a full 24-player match (12 v 12) with the host
# data layout: state words, then a player slot per bot, then the kit lookup's handle
STATE, MANAGER, TICK, SLOTS = 0x0, 0x4, 0x8, 0x10
HANDLE = SLOTS + 4 * MAX_BOTS + 4
FRAME = 0x1E0                # stack frame: an input frame buffer at +0x80 (0x100 bytes, 16-aligned); saves (to -0x50) above it
BUF = 0x80
DT = BUF + 0x104             # the saved time step (float), between the buffer and the saved registers
THROTTLE = 0x00000000        # forward input in every bot frame (float bits; 0x3F800000 = 1.0 walks forward)

TEAMS = {1: 'US', 2: 'RU'}   # asset folder per team (Japan's soldiers keep BFBC2's RU name)
KITS = {'Rifleman': 'Assault', 'Infantry': 'Support', 'Scout': 'Specialist'}
FRIENDLY, ENEMY = 1, 2       # a bot's side, relative to the host's team (read when the bots are created)
CLASSES = ['Rifleman', 'Infantry', 'Scout']
# a full match: 11 on the host's side and 12 against, the classes in turn
DEFAULT_BOTS = ([(FRIENDLY, CLASSES[k % 3]) for k in range(11)] + [(ENEMY, CLASSES[k % 3]) for k in range(12)])

CODE_SOURCE = '''
hook:
    mflr r12
    stw r12, -8(r1)
    std r23, -0x50(r1)
    std r24, -0x48(r1)
    std r25, -0x40(r1)
    std r26, -0x38(r1)
    std r27, -0x30(r1)
    std r28, -0x28(r1)
    std r29, -0x20(r1)
    std r30, -0x18(r1)
    std r31, -0x10(r1)
    stwu r1, -FRAME(r1)
    stfs f1, DT(r1)          # the server's time step (82391930 passes it to 8238eb68 in f1), for the frames
    bl 0x8238eb68            # the server's own player update (r3, f1 as the caller set them)
    la r31, DATA
    bl 0x82349d78            # server context
    lwz r30, 0x28(r3)        # player manager
    cmpwi r30, 0
    beq out
    lwz r4, 0x54(r30)        # players: begin, end
    lwz r5, 0x58(r30)
    cmplw r4, r5
    beq forget               # nobody in the match (it ended): the bots are gone
    lwz r3, MANAGER(r31)
    cmplw r3, r30
    bne forget               # another match's player manager
    lwz r3, STATE(r31)
    cmpwi r3, 0
    bne respawn
    lwz r4, 0(r4)            # the first player (the host's own) has a soldier: the match is running
    lwz r5, 0x120(r4)
    cmpwi r5, 0
    beq out
    lwz r25, 0x30(r4)        # the host's team: bots are friendly (the same) or enemy (3 - it)
    mr r5, r4                # report: the host's player and team (Xenia logs DbgPrint)
    lwz r6, 0x30(r4)
    la r3, FMT_HOST
    mr r4, r5
    mr r5, r6
    bl 0x829fa7ec
    li r3, 1
    stw r3, STATE(r31)       # create once per match (the data area is per game session: see AGENT_PROGRESS)
    la r29, BOTS
    la r28, SLOTS_ADDR
create:
    lwz r3, 0(r29)           # side (FRIENDLY or ENEMY), 0 ends the table
    cmpwi r3, 0
    beq respawn
    mr r24, r25              # the bot's team
    cmpwi r3, FRIENDLY
    beq side_known
    li r24, 3
    subf r24, r25, r24
side_known:
    mr r3, r30
    li r4, 0
    bl 0x82387ef0            # createPlayer
    cmpwi r3, 0
    beq respawn              # server full
    stw r3, 0(r28)
    mr r4, r3
    mr r3, r30
    lwz r5, 12(r29)
    bl 0x8238efd8            # addPlayer(manager, player, name)
    bl 0x82349d78            # as the network join does next (823af188): register the player with the
    lwz r3, 0x44(r3)         # server's score and stats managers, 8240dfe0(context + 0x44, player)
    cmpwi r3, 0
    beq input
    lwz r4, 0(r28)
    bl 0x8240dfe0
input:
    li r3, 0x168
    bl 0x82627d10            # memory for an input state
    cmpwi r3, 0
    beq team
    bl 0x822c1478            # construct it
    mr r4, r3
    lwz r3, 0(r28)
    bl 0x8236f230            # player + 0x118 = it
team:
    lwz r3, 0(r28)
    bl 0x82375130            # ready to spawn
    lwz r3, 0(r28)
    mr r4, r24
    bl 0x82374f90            # setTeam
    li r4, 0
    stw r4, HANDLE(r31)
    stw r4, HANDLE_4(r31)
    stw r4, HANDLE_8(r31)
    stw r4, HANDLE_C(r31)
    addi r3, r31, HANDLE
    lwz r4, 4(r29)           # the kit's name for team 1 (USMC) or team 2 (Japan)
    cmpwi r24, 1
    beq kit_named
    lwz r4, 8(r29)
kit_named:
    bl 0x82378988            # the kit's SoldierEntityData, by asset name
    lwz r4, HANDLE(r31)
    cmpwi r4, 0
    beq next
    lwz r3, 0(r28)
    addi r3, r3, 0x1f4
    bl 0x82373a28            # player kit = it
next:
    la r3, FMT_CREATED       # report: the bot, its team and kit
    lwz r4, 0(r28)
    lwz r5, 0x30(r4)
    lwz r6, 0x1f4(r4)
    bl 0x829fa7ec
    addi r29, r29, 16
    addi r28, r28, 4
    b create
respawn:
    lwz r3, TICK(r31)        # a server tick count, for the position reports
    addi r3, r3, 1
    stw r3, TICK(r31)
    andi. r3, r3, 63         # every 64 ticks also report the host's soldier (the first player), to check the
    bne bots_loop            # position reading against a soldier that is known to move
    lwz r4, 0x54(r30)
    lwz r4, 0(r4)
    lwz r3, 0x120(r4)
    cmpwi r3, 0
    beq bots_loop
    bl 0x822a7bb0
    lwz r5, 0x30(r3)
    lwz r6, 0x34(r3)
    lwz r7, 0x38(r3)
    lwz r4, 0x54(r30)
    lwz r4, 0(r4)
    la r3, FMT_HOST_POSITION
    bl 0x829fa7ec
bots_loop:
    la r28, SLOTS_ADDR
    li r29, MAX_BOTS
spawn:
    lwz r27, 0(r28)
    cmpwi r27, 0
    beq skip
    lwz r3, 0x118(r27)       # its input state: one neutral frame per tick, as the server makes for a
    cmpwi r3, 0              # connection with no input queued (823af4a0 -> 822bd4a8, 823a1f80, 822c15d0)
    beq spawn_it
    addi r3, r1, BUF
    bl 0x822bd4a8            # a cleared frame
    lwz r3, 0x118(r27)
    lwz r4, 0x160(r3)        # the current frame:
    lwz r5, 0x98(r4)
    addi r5, r5, 1
    stw r5, BUF_98(r1)       # its sequence number + 1
    lwz r5, DT(r1)
    stw r5, BUF_80(r1)       # the frame's time step (+0x80: 822f1d70 stores its f1 there, 822ba678); copied
                             # from the cleared first frame it stayed 0, and the soldiers never moved
                             # (with the AI flag they settled onto the deck but ignored forward input)
    lwz r5, 0x84(r4)
    stw r5, BUF_84(r1)
    li32 r5, THROTTLE        # test: EIAThrottle (action 0, an analog float at frame + 8): walk forward
    stw r5, BUF_THROTTLE(r1)

    lwz r3, 0x118(r27)
    addi r4, r1, BUF
    bl 0x822c15d0            # push it
    lwz r3, 0x120(r27)       # and step the soldier with it, as the network path does after each frame it
    cmpwi r3, 0              # drains (823b2ed4): soldier virtual +0x104 (822f05c8: facing, jump and velocity
    beq spawn_it             # (+0x110), the character physics with frame dt, then placement (+0x114)),
    lwz r11, 0(r3)           # entry index 0. Nothing else steps a soldier: the physics world skips characters
    lwz r11, 0x104(r11)      # while Physics.SingleStepCharacter is on (8253e4c8), and the per-tick update
    mtctr r11                # 822f1d70 runs only +0x114, and only for AI-flagged players.
    li r4, 0
    bctrl
    lwz r3, 0x120(r27)       # report: every 64 ticks, where the server has the bot's soldier
    cmpwi r3, 0              # (its transform, 822a7bb0, translation row at +0x30, as raw float bits)
    beq spawn_it
    lwz r4, TICK(r31)
    andi. r4, r4, 63
    bne spawn_it
    bl 0x822a7bb0
    lwz r5, 0x30(r3)
    lwz r6, 0x34(r3)
    lwz r7, 0x38(r3)
    lwz r3, 0x120(r27)
    lwz r8, 0x328(r3)        # the soldier's throttle limit (822edb28 clamps action 0 to it)
    li r9, 0
    li r10, 0
    lwz r3, 0x118(r27)
    cmpwi r3, 0
    beq report
    lwz r3, 0x160(r3)        # the bot's current input frame: throttle (+0x08) and time step (+0x80)
    lwz r9, 8(r3)
    lwz r10, 0x80(r3)
report:
    mr r4, r27
    la r3, FMT_POSITION
    bl 0x829fa7ec
spawn_it:
    lwz r4, 0x120(r27)       # no soldier yet (or dead): ask to spawn at its team's base
    cmpwi r4, 0
    bne skip
    bl 0x82349d78            # the spawn lists' owner, as 82382720 finds it (0x8238278c):
    lwz r11, 0x2c(r3)        # *(*(context + 0x2c) + 0x74) + 8
    lwz r3, 0x74(r11)
    lwz r26, 8(r3)
    li r25, 1                # search the lists of teams 1 and 2 for a spawn of the bot's own team
lists:
    mr r3, r26
    mr r4, r25
    bl 0x82343f68            # that team's list: begin, end
    lwz r24, 0(r3)
    lwz r23, 4(r3)
entries:
    cmplw r24, r23
    beq next_list
    lwz r3, 0(r24)           # a spawn entity
    addi r24, r24, 4
    cmpwi r3, 0
    beq entries
    lwz r4, 0x14(r3)         # its data (SoldierSpawnEntityData; 8236b688 reads it so) and the data's Team
    cmpwi r4, 0              # (+0x88, read so by the constructor 82362a40)
    beq entries
    lwz r4, 0x88(r4)
    lwz r5, 0x30(r27)
    cmpw r4, r5
    bne entries
    bl 0x822a83a8            # the bot's own base: its spawn id, as 82382720 makes it
    mr r26, r3
    b request
next_list:
    addi r25, r25, 1
    cmpwi r25, 3
    bne lists
    li r26, 0                # none found: the server's own default
request:
    mr r3, r27
    mr r4, r26
    bl 0x82382720
    cmpwi r3, 0
    beq skip
    la r3, FMT_SPAWNED       # report a spawn: the bot, its team, the spawn asked for, the soldier
    mr r4, r27
    lwz r5, 0x30(r27)
    mr r6, r26
    lwz r7, 0x120(r27)
    bl 0x829fa7ec
skip:
    addi r28, r28, 4
    addi r29, r29, -1
    cmpwi r29, 0
    bne spawn
    b out
forget:                      # no bots this match yet: clear the state and slots, remember this manager
    li r3, 0
    stw r3, STATE(r31)
    stw r30, MANAGER(r31)
    la r28, SLOTS_ADDR
    li r29, MAX_BOTS
clear:
    stw r3, 0(r28)
    addi r28, r28, 4
    addi r29, r29, -1
    cmpwi r29, 0
    bne clear
out:
    addi r1, r1, FRAME
    lwz r12, -8(r1)
    mtlr r12
    ld r23, -0x50(r1)
    ld r24, -0x48(r1)
    ld r25, -0x40(r1)
    ld r26, -0x38(r1)
    ld r27, -0x30(r1)
    ld r28, -0x28(r1)
    ld r29, -0x20(r1)
    ld r30, -0x18(r1)
    ld r31, -0x10(r1)
    blr
FMT_HOST:
    .string "rs-bots: host player %08x team %d"
FMT_CREATED:
    .string "rs-bots: bot %08x team %d kit %08x"
FMT_HOST_POSITION:
    .string "rs-bots: host %08x soldier position %08x %08x %08x"
FMT_POSITION:
    .string "rs-bots: bot %08x soldier position %08x %08x %08x limit %08x throttle %08x dt %08x"
FMT_SPAWNED:
    .string "rs-bots: spawned %08x team %d at spawn id %08x soldier %08x"
'''


def string_record(text, at):
    """A {begin, end, capacity end} string (end past the NUL, as the game's own strings) followed by its text."""
    raw = text.encode('ascii') + b'\0'
    raw += b'\0' * (-len(raw) % 4)
    chars = at + 12
    return struct.pack('>III', chars, chars + len(text) + 1, chars + len(text) + 1) + raw


def build(bots=DEFAULT_BOTS):
    """(patch words [(address, value, comment)], code bytes, data bytes) for the given [(team, class)]."""
    if not 1 <= len(bots) <= MAX_BOTS:
        raise ValueError(f'1 to {MAX_BOTS} bots')
    for side, kit in bots:
        if side not in (FRIENDLY, ENEMY) or kit not in KITS:
            raise ValueError(f'unknown bot {side} {kit}')
    symbols = {'DATA': DATA, 'STATE': STATE, 'MANAGER': MANAGER, 'TICK': TICK, 'SLOTS_ADDR': DATA + SLOTS, 'HANDLE': HANDLE, 'HANDLE_4': HANDLE + 4,
               'HANDLE_8': HANDLE + 8, 'HANDLE_C': HANDLE + 12, 'FRAME': FRAME, 'BUF': BUF, 'BUF_98': BUF + 0x98,
               'BUF_80': BUF + 0x80, 'DT': DT, 'BUF_THROTTLE': BUF + 8, 'BUF_BUTTONS_LO': BUF + 0x7C, 'THROTTLE': THROTTLE, 'BUF_84': BUF + 0x84, 'MAX_BOTS': MAX_BOTS, 'FRIENDLY': FRIENDLY, 'BOTS': 0}
    code, _ = ppcasm.assemble(CODE_SOURCE, CODE, symbols)
    table_at = CODE + len(code)
    strings_at = table_at + 16 * len(bots) + 4
    strings, table = b'', b''
    kit_strings = {}
    for kit in sorted(set(k for _, k in bots)):    # each kit's name for team 1 and team 2, once
        for team, folder in TEAMS.items():
            kit_strings[kit, team] = strings_at + len(strings)
            strings += string_record(f'Objects/Soldiers/{folder}/{KITS[kit]}', kit_strings[kit, team])
    for n, (side, kit) in enumerate(bots, 1):
        name_at = strings_at + len(strings)
        strings += string_record(f'Bot {n} {kit}', name_at)
        table += struct.pack('>IIII', side, kit_strings[kit, 1], kit_strings[kit, 2], name_at)
    table += struct.pack('>I', 0)
    symbols['BOTS'] = table_at
    code, _ = ppcasm.assemble(CODE_SOURCE, CODE, symbols)
    if CODE + len(code) != table_at:
        raise AssertionError('code size changed between passes')
    blob = code + table + strings
    if CODE + len(blob) > CODE_END:
        raise ValueError(f'the bot code needs {len(blob):#x} bytes, the cave has {CODE_END - CODE:#x}')
    hook, _ = ppcasm.assemble(f'bl {CODE:#x}', HOOK)
    words = [(HOOK, struct.unpack('>I', hook)[0], f'bl bot code (was {HOOK_ORIGINAL:#010x}, bl 0x8238eb68)')]
    for k in range(0, len(blob), 4):
        words.append((CODE + k, struct.unpack_from('>I', blob, k)[0], 'bot code' if k < len(code) else 'bot table and names'))
    return words, code, table + strings


def patch_toml(bots=DEFAULT_BOTS):
    words, code, _ = build(bots)
    friendly = sum(1 for s, _ in bots if s == FRIENDLY)
    names = f'{friendly} on the host side, {len(bots) - friendly} against'
    lines = [HEADER + ' Experimental; addresses are for module hash 872BBE31C0FBA21B.',
             'title_name = "Battlefield 1943"', 'title_id = "5841097E"', 'hash = "872BBE31C0FBA21B"', '',
             '[[patch]]', '    name = "Experiment: offline bots (they spawn and stand; no decisions yet)"',
             f'    desc = "{len(bots)} server-side bots: {names}. They join, take their team\'s kit and spawn; they do not move yet."',
             '    author = "bf1943-xenia-kit"', '    is_enabled = true', '']
    for address, value, comment in words:
        lines += ['    [[patch.be32]]', f'        # {comment}', f'        address = {address:#010x}', f'        value = {value:#010x}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    sys.stdout.write(patch_toml())
